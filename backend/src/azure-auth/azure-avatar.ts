import type { AzureHttpGetter, AzureTokenGetter } from '../repo/azure-repo-lister.js';

/**
 * The signed-in Microsoft account's Azure DevOps profile picture. The OAuth
 * token stays in the backend; the UI only receives an image `data:` URL, which
 * the desktop CSP already permits, so no remote image host is allowed.
 */
export interface AzureAvatar {
  /** A `data:image/...;base64,` URL, or null when unavailable. */
  dataUrl: string | null;
  /** True when Azure DevOps generated a placeholder rather than a real photo. */
  autoGenerated: boolean;
}

export interface AzureAvatarDeps {
  token: AzureTokenGetter;
  httpGet: AzureHttpGetter;
}

/** Org-agnostic profile avatar; the JSON form carries base64 image bytes. */
export const AZURE_AVATAR_URL =
  'https://vssps.dev.azure.com/_apis/profile/profiles/me/avatar?size=large&api-version=7.1-preview.1';

/** Bounds the payload forwarded to the UI (a large avatar is ~150 KB). */
const MAX_BASE64_LENGTH = 1_000_000;

const NONE: AzureAvatar = { dataUrl: null, autoGenerated: false };

/** Identify the image type from its leading bytes rather than trusting input. */
function imageType(base64: string): string | null {
  if (base64.startsWith('iVBORw0KGgo')) return 'image/png';
  if (base64.startsWith('/9j/')) return 'image/jpeg';
  if (base64.startsWith('R0lGOD')) return 'image/gif';
  return null;
}

export function parseAzureAvatar(body: unknown): AzureAvatar {
  if (!body || typeof body !== 'object') return NONE;
  const { value, isAutoGenerated } = body as { value?: unknown; isAutoGenerated?: unknown };
  if (typeof value !== 'string' || !value || value.length > MAX_BASE64_LENGTH || !/^[A-Za-z0-9+/]+={0,2}$/.test(value)) {
    return NONE;
  }
  const type = imageType(value);
  if (!type) return NONE;
  return { dataUrl: `data:${type};base64,${value}`, autoGenerated: isAutoGenerated === true };
}

/** Fetch the avatar with the organization's cached credential; never throws for absence. */
export async function fetchAzureAvatar(deps: AzureAvatarDeps, org: string): Promise<AzureAvatar> {
  const token = await deps.token(org);
  if (!token) return NONE;
  const response = await deps.httpGet(AZURE_AVATAR_URL, token);
  return response.status === 200 ? parseAzureAvatar(response.body) : NONE;
}
