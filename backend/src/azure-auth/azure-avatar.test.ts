import { describe, expect, it, vi } from 'vitest';
import { AZURE_AVATAR_URL, fetchAzureAvatar, parseAzureAvatar } from './azure-avatar.js';

const PNG = 'iVBORw0KGgoAAAANSUhEUg==';

describe('parseAzureAvatar', () => {
  it('returns typed data URLs for real and generated pictures', () => {
    expect(parseAzureAvatar({ value: PNG, isAutoGenerated: false }))
      .toEqual({ dataUrl: `data:image/png;base64,${PNG}`, autoGenerated: false });
    expect(parseAzureAvatar({ value: '/9j/4AAQ', isAutoGenerated: true }))
      .toEqual({ dataUrl: 'data:image/jpeg;base64,/9j/4AAQ', autoGenerated: true });
    expect(parseAzureAvatar({ value: 'R0lGODlh' }).dataUrl).toBe('data:image/gif;base64,R0lGODlh');
  });

  it.each([
    ['missing body', null],
    ['non-object body', 'text'],
    ['missing value', {}],
    ['empty value', { value: '' }],
    ['non-base64 value', { value: 'iVBOR"><script>' }],
    ['unknown image type', { value: 'PHN2Zz4=' }],
    ['oversized value', { value: `iVBORw0KGgo${'A'.repeat(1_000_000)}` }],
  ])('rejects a %s', (_label, body) => {
    expect(parseAzureAvatar(body)).toEqual({ dataUrl: null, autoGenerated: false });
  });
});

describe('fetchAzureAvatar', () => {
  it('uses the organization credential against the profile avatar API', async () => {
    const token = vi.fn(async () => 'token');
    const httpGet = vi.fn(async () => ({ status: 200, body: { value: PNG, isAutoGenerated: false } }));
    await expect(fetchAzureAvatar({ token, httpGet }, 'contoso'))
      .resolves.toEqual({ dataUrl: `data:image/png;base64,${PNG}`, autoGenerated: false });
    expect(token).toHaveBeenCalledWith('contoso');
    expect(httpGet).toHaveBeenCalledWith(AZURE_AVATAR_URL, 'token');
  });

  it('returns no picture when signed out or the API refuses', async () => {
    const httpGet = vi.fn(async () => ({ status: 401, body: null }));
    await expect(fetchAzureAvatar({ token: async () => null, httpGet }, 'contoso'))
      .resolves.toEqual({ dataUrl: null, autoGenerated: false });
    expect(httpGet).not.toHaveBeenCalled();
    await expect(fetchAzureAvatar({ token: async () => 'token', httpGet }, 'contoso'))
      .resolves.toEqual({ dataUrl: null, autoGenerated: false });
  });
});
